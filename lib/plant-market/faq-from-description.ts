/** Derive up to five factual FAQs from seller-authored description sections.
 * No AI/API calls, no fabricated answers, and no HTML from answers is injected. */
const FAQ_HEADING = "পণ্য সম্পর্কে সাধারণ প্রশ্নোত্তর (FAQ)";
const FAQ_HEAD_REGEX = /<h2[^>]*>\s*পণ্য সম্পর্কে সাধারণ প্রশ্নোত্তর \(FAQ\)\s*<\/h2>/i;
const escapeHtml = (text: string) => text.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

export function appendFiveFaq(description: string, productName: string): string {
  if (typeof DOMParser === "undefined" || !description.trim()) return description;
  // Remove only the FAQ section generated by this feature, preserving seller-authored content above it.
  const match = FAQ_HEAD_REGEX.exec(description);
  const base = match ? description.slice(0, match.index) : description;
  const doc = new DOMParser().parseFromString(base, "text/html");
  const headings = Array.from(doc.body.querySelectorAll("h2"));
  const sections = headings.map((heading) => {
    const title = (heading.textContent || "").trim();
    let sibling = heading.nextElementSibling;
    const parts: string[] = [];
    while (sibling && sibling.tagName !== "H2") {
      const value = (sibling.textContent || "").trim().replace(/\s+/g, " ");
      if (value) parts.push(value);
      sibling = sibling.nextElementSibling;
    }
    return { title, answer: parts.join(" ").slice(0, 360) };
  }).filter((section) => section.title && section.answer.length >= 30);
  const rules: Array<[RegExp, string]> = [
    [/বৈশিষ্ট্য|বিশেষত্ব|পরিচিতি/i, `${productName} গাছের প্রধান বৈশিষ্ট্য কী?`],
    [/কোথায়|স্থান|ব্যবহার/i, `${productName} কোথায় লাগানো ভালো?`],
    [/আলো|সূর্যালোক|রোদ/i, `${productName} গাছে কেমন আলো প্রয়োজন?`],
    [/পানি|জল|সেচ/i, `${productName} গাছে কীভাবে পানি দিতে হয়?`],
    [/ফুল ফোট|ফুল আস|মৌসুম/i, `${productName} গাছে কখন ফুল আসে?`],
    [/রোপণ|লাগানো/i, `${productName} কীভাবে রোপণ করবেন?`],
    [/কেনার আগে|কেনার সময়/i, `${productName} কেনার আগে কী যাচাই করবেন?`],
    [/পরিচর্যা|যত্ন/i, `${productName} গাছের যত্ন কীভাবে নেবেন?`],
  ];
  const used = new Set<number>();
  const faq: Array<{ question: string; answer: string }> = [];
  for (const [pattern, question] of rules) {
    const index = sections.findIndex((section, i) => !used.has(i) && pattern.test(section.title));
    if (index === -1) continue;
    used.add(index);
    faq.push({ question, answer: sections[index].answer });
    if (faq.length === 5) break;
  }
  // Never pad missing FAQs with invented facts or generic filler.
  if (faq.length !== 5) return description;
  const rendered = "<h2>" + FAQ_HEADING + "</h2>" +
    faq.map(({question, answer}) => "<h3>" + escapeHtml(question) + "</h3><p>" + escapeHtml(answer) + "</p>").join("");
  return base + rendered;
}

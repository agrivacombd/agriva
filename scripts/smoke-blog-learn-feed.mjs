import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import ts from "typescript";
const read = p => readFileSync(new URL("../"+p,import.meta.url),"utf8");
const feed=read("lib/learn/blog-feed.ts");
const browser=read("app/blog/articles-browser.tsx");
const page=read("app/blog/page.tsx");
const detail=read("app/blog/[slug]/page.tsx");
const sitemap=read("app/sitemap.ts");
const transformed=ts.transpileModule(feed,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
assert.match(feed,/LESSONS\.map\(lesson/);
assert.match(feed,/href: `\/learn\/\$\{lesson.slug\}`/);
assert.match(feed,/source: "learn"/);
assert.match(browser,/href=\{article.href\}/);
assert.match(browser,/Learn গাইড/);
assert.match(browser,/value: "blog", label: "প্রবন্ধ"/, "Blog source filter should be clearly labeled");
assert.match(browser,/কৃষি প্রবন্ধ/, "Featured blog articles should retain their descriptive category label");
assert.match(page,/getLearnBlogFeed\(\)/);
assert.doesNotMatch(page,/const articles: Article\[\]/);
assert.match(page,/\.eq\("status", "published"\)/);
assert.match(page,/article.href/);
assert.match(detail,/permanentRedirect\(destination\)/);
assert.match(detail,/\.eq\("status","published"\)/);
assert.doesNotMatch(detail,/const articles = \[/);
assert.match(sitemap,/LESSONS\.map\(\(lesson\)/);
assert.doesNotMatch(sitemap, /\/blog\/\$\{slug\}/);
assert.doesNotMatch(read("components/admin/shell/OrderNotificationBell.tsx"),/const browserKey=cursorKey.current/);
assert.ok(transformed.includes("getLearnBlogFeed"));
console.log("Learn feed source, canonical URLs, published-only CMS, legacy redirects and clickable cards passed.");

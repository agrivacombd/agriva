import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const sql=read("supabase/migrations/20261116133541_admin_content_draft_trash_restore_and_audited_permanent_delete.sql");
const api=read("app/admin/content-drafts/trash/route.ts");
const buttons=read("app/admin/content-drafts/ContentRemovalActions.tsx");
for(const field of ["deleted_at","deleted_by","deleted_from_status"])assert.ok(sql.includes(field));
assert.match(sql,/ON DELETE|on delete/);
assert.match(sql,/deleted_at is null/);
assert.match(sql,/permanently_deleted/);
assert.match(api,/requireAdminApi\("content.edit"\)/);
assert.match(api,/requireAdminApi\("content.publish"\)/);
assert.match(api,/\.delete\(\)/);
assert.match(api,/\.eq\("deleted_at",entry.deleted_at\)/);
assert.match(api,/payload\.confirmSlug!==entry\.slug/);
assert.match(api,/payload\?\.confirmPermanent!==true/);
assert.match(api,/revalidatePath\("\/blog\/"\+entry.slug\)/);
assert.doesNotMatch(api,/service_role|SUPABASE_SERVICE_ROLE/);
assert.match(buttons,/window\.prompt\("PERMANENT DELETE/);
assert.match(buttons,/Restore as Draft/);
assert.match(buttons,/Permanently Delete/);
assert.match(buttons,/router\.refresh\(\)/);
console.log("Content trash, restore, permanent deletion audit and confirmations are guarded.");

import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import ts from "typescript";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const src=read("lib/marketplace/personalization.ts");
const code=ts.transpileModule(src,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const mod=await import("data:text/javascript;base64,"+Buffer.from(code).toString("base64"));
const id="5bc9eeea-4d10-4d91-ae74-67b7a59c26ef",now=Date.now();
const products=Array.from({length:20},(_,i)=>({id:i===7?id:"p"+i,category_slug:i<12?"seeds":"fertilizers",subcategory_slug:i<12?"vegetables":"organic",stock:i===19?0:10,price:120}));
assert.deepEqual(mod.suggestForBrowser(products,[],[],now).ordered,products,"Cold start preserves previous ranking");
assert.equal(mod.suggestForBrowser(products,[],[],now).suggested.length,0);
const history=[{kind:"view",id,category:"seeds",subcategory:"vegetables",time:now}];
const result=mod.suggestForBrowser(products,history,[],now);
assert.ok(result.suggested.some(p=>p.id===id),"Viewed product contributes a recommendation");
assert.ok(result.ordered.findIndex(p=>p.id===id)<7,"Recent interest can modestly change default relevance");
assert.equal(result.ordered.at(-1).stock,0,"Out of stock remains last");
assert.ok(result.suggested.every(p=>p.stock>0 && p.price!==null));
assert.equal(mod.suggestForBrowser(products,[{...history[0],time:now-31*86400000}],[],now).suggested.length,0,"Old signals expire");
assert.ok(mod.cleanHistory(Array.from({length:500},(_,i)=>({...history[0],time:now-i*60000})),now).length<=80);
for(const token of ["localStorage","doNotTrack","globalPrivacyControl","Math.min(16"])assert.ok(src.includes(token));
assert.doesNotMatch(src,/fetch\(|supabase|\/api\//i,"No extra backend API");
const core=read("components/marketplace/MarketplaceCore.tsx");
assert.ok(core.includes('sort === "recommended"'));
assert.ok(core.includes("suggestForBrowser(filtered"));
assert.ok(core.includes("setPersonalSort"));
assert.ok(read("app/marketplace/page.tsx").includes("get_ranked_marketplace_products"));
assert.ok(read("supabase/migrations/20261114003000_product_rank_hybrid_retention.sql").includes("42 * ln"));
console.log("Marketplace local personalization and legacy ranking checks passed.");

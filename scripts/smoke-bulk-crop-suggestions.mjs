import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import ts from "typescript";
const options={compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}};
const extraSource=readFileSync("lib/bulk-rfq/bangladesh-agri-market-catalog.ts","utf8");
const extraJs=ts.transpileModule(extraSource,options).outputText;
const extraUrl="data:text/javascript;base64,"+Buffer.from(extraJs).toString("base64");
const source=readFileSync("lib/bulk-rfq/bangladesh-crop-suggestions.ts","utf8");
const output=ts.transpileModule(source,options).outputText.replace("./bangladesh-agri-market-catalog",extraUrl);
const {BD_CROP_SUGGESTIONS,cropSearchKey,suggestCrops}=await import("data:text/javascript;base64,"+Buffer.from(output).toString("base64"));
assert.ok(BD_CROP_SUGGESTIONS.length>=450,"A comprehensive Bangladesh seed, market and farm-input vocabulary is expected");
assert.ok(BD_CROP_SUGGESTIONS.filter(x=>x.category==="বীজ").length>=140,"Seed types must be prominent");
assert.ok(suggestCrops("টমেটো").some(x=>x.name==="টমেটো বীজ"),"Bangla typing should find tomato seeds");
assert.ok(suggestCrops("Tomato").some(x=>x.name==="টমেটো বীজ"),"English alias should find Bangla name");
assert.ok(suggestCrops("চিয়া").some(x=>x.name==="চিয়া সিড"),"Chia seed should be supported");
assert.ok(suggestCrops("bij").some(x=>x.name.includes("বীজ")),"Romanized bij should show seed suggestions");
assert.ok(suggestCrops("BR28").some(x=>x.name==="ব্রি ধান২৮ বীজ"),"BRRI aliases should be searchable");
assert.equal(cropSearchKey("ধান ২৮"),cropSearchKey("ধান 28"),"Bangla and Latin digits must match");
assert.deepEqual(suggestCrops("totally-unlisted-crop"),[],"Customers may write a new custom name");
assert.ok(suggestCrops("সুদর্শন").some(x=>x.name.includes("সুদর্শন")),"Siddique Bazar-connected hybrid seed reference");
assert.ok(suggestCrops("কুইন্টাল").length===0,"Autocomplete only suggests products, not units");
assert.ok(suggestCrops("ইউরিয়া").some(x=>x.category==="সার"),"Fertilizer category");
assert.ok(suggestCrops("নেপিয়ার").some(x=>x.name.includes("নেপিয়ার")),"Fodder seed category");
assert.ok(suggestCrops("পেটুনিয়া").some(x=>x.category==="ফুলের বীজ"),"Flower seed category");
assert.ok(suggestCrops("সিডলিং ট্রে").some(x=>x.category==="কৃষি উপকরণ"),"Nursery items");
assert.equal(new Set(suggestCrops("বীজ",BD_CROP_SUGGESTIONS,100).map(x=>cropSearchKey(x.name))).size,suggestCrops("বীজ",BD_CROP_SUGGESTIONS,100).length,"No duplicated results");
assert.ok(suggestCrops("ধান").length<=8,"Suggestions should be bounded");
console.log("AGRIVA crop name autocomplete regression checks passed");

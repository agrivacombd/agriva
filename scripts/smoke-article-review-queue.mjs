import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const queue=read("app/admin/articles/page.tsx");
const client=read("app/admin/articles/ArticleQueueClient.tsx");
const legacy=read("app/admin/articles/[id]/page.tsx");
assert.match(queue,/requireAdminPage\("content.read"\)/);
assert.match(queue,/\.from\("content_drafts"\)/);
assert.match(queue,/\.eq\("content_type","article"\)/);
assert.doesNotMatch(queue,/\.from\("article_drafts"\)/);
assert.match(client,/statusLabels/);
assert.match(client,/aria-label="Article status filter"/);
assert.match(client,/ArticleQueueEntry/);
assert.match(client,/setOnlyIssues/);
assert.match(client,/\/admin\/content-drafts\?draft=/);
assert.match(client,/Published/);
assert.match(legacy,/requireAdminPage\("content.read"\)/);
assert.doesNotMatch(legacy,/\.from\("article_drafts"\)/);
assert.match(legacy,/redirect\("\/admin\/articles"\)/);
console.log("Article Queue reads the production CMS only, filters safely and retains authenticated legacy redirects.");

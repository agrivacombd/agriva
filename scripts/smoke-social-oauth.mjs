import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = (file) => readFileSync(new URL("../" + file, import.meta.url), "utf8");
const login = read("app/login/page.tsx");
const signup = read("app/signup/page.tsx");
const buttons = read("components/auth/SocialAuthButtons.tsx");
const callback = read("app/auth/callback/route.ts");
const safeNext = read("lib/auth/safe-next.ts");
const profile = read("lib/auth/social-profile.ts");
assert.match(login, /<SocialAuthButtons/, "login must show social sign-in");
assert.match(signup, /<SocialAuthButtons/, "signup must show social sign-in");
assert.match(buttons, /continueWith\("google"\)/, "Google provider");
assert.match(buttons, /continueWith\("facebook"\)/, "Facebook provider");
assert.match(buttons, /signInWithOAuth/, "Supabase-managed OAuth");
assert.match(buttons, /new URL\("\/auth\/callback", window.location.origin\)/, "same-origin callback");
assert.match(callback, /exchangeCodeForSession\(code\)/, "PKCE exchange on server");
assert.match(callback, /fillMissingSocialProfileName\(supabase, data.user\)/, "social profile name sync");
assert.match(safeNext, /resolved.origin !== "https:\/\/agriva.com.bd"/, "reject external redirect");
assert.match(profile, /\.eq\("id", user.id\)/, "self-only profile enrichment");
assert.match(profile, /full_name.is.null,full_name.eq\./, "preserve user-entered name");
assert.doesNotMatch(profile, /selected_roles|updateUser\(/, "no permission changes in social sync");
console.log("AGRIVA Google/Facebook OAuth regression checks passed.");

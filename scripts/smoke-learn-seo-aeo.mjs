import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import ts from "typescript";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const hub=read("app/learn/page.tsx");
const article=read("app/learn/[slug]/page.tsx");
const docs=read("lib/learn/lessons.ts");
const sitemap=read("app/sitemap.ts");
const ci=read(".github/workflows/ci.yml");
for(const type of ["CollectionPage","BreadcrumbList","ItemList"]) assert.match(hub,new RegExp('"' + type + '"'),type);
for(const path of ["/learn/plant-disease","/learn/plant-science","/blog","/crop-calendar","/agriculture-calculators"])assert.ok(hub.includes(path),"Missing internal link: "+path);
assert.match(hub,/robots:\{index:true,follow:true/);
assert.match(hub,/alternates:\{canonical\}/);
assert.match(hub,/questions\.map\(item=>/);
assert.match(hub,/numberOfItems:allGuides\.length/);
assert.match(hub,/safeJson=JSON\.stringify\(structured\)\.replace/);
assert.match(hub,/rel="noopener noreferrer"|<Link href=|<a href=/);
assert.match(article,/await params/g);
assert.match(article,/"@type":"Article"/);
assert.match(article,/"@type":"BreadcrumbList"/);
assert.match(article,/\.replace\(\/<\/g/);
assert.match(article,/isAccessibleForFree:true/);
assert.match(docs,/slug: "rice-cultivation"/);
assert.match(sitemap,/LESSONS\.map\(\(lesson\)/);
assert.match(ci,/smoke-learn-seo-aeo\.mjs/);
const jsx=ts.transpileModule(hub,{fileName:"page.tsx",compilerOptions:{jsx:ts.JsxEmit.Preserve,target:ts.ScriptTarget.ES2022, module:ts.ModuleKind.ESNext},reportDiagnostics:true});
assert.equal(jsx.diagnostics?.length||0,0,"Hub must parse in TypeScript");
const guide=ts.transpileModule(article,{fileName:"page.tsx",compilerOptions:{jsx:ts.JsxEmit.Preserve,target:ts.ScriptTarget.ES2022, module:ts.ModuleKind.ESNext},reportDiagnostics:true});
assert.equal(guide.diagnostics?.length||0,0,"Guide must parse in TypeScript");
console.log("Learn CollectionPage, breadcrumb, ItemList, Q&A and SEO guide metadata checks passed.");
